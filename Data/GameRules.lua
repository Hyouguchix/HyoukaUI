-- HyoukaUI: правила игры в одном месте (plan 2.2, GameRules): полы кулдаунов, горизонты расписания,
-- обязательные покрытия частей HUD. Только данные и две мелкие функции, без состояния.
-- Версия правил: если игра изменит числа, правится только этот файл.
--
-- Чего здесь НЕТ и почему: лимиты призывов и зум миникарты в плане упомянуты, но числа не сняты
-- ни кодом движка, ни игрой. Они лежат как nil с пометкой [НЕ ПРОВЕРЕНО], выдумывать их нельзя.

local H = HyoukaUI

local R = {}
H.Rules = R

R.version = "azs-0.141"        -- [НЕ ПРОВЕРЕНО] версия игры, под которую снят дамп (azs-api.md, раздел 4 п. 8: упоминание до 0.141)

-- Кулдауны. Движок округляет cdmax до 0.1 с, поэтому "пол" 0.25 с приходит как 0.2
-- (FloorHourglass.lua:15-22 в SurvivorUI, azs-api.md 2.3). Показываем 0.25.
R.cdFloorRaw = 0.2
R.cdFloor = 0.25
-- Откат короче этого не рисуем шторкой (plan 6.3: счетчик показов шторки у откатов < 1.5 с).
R.cdShortShutter = 1.5

-- Расписание боссов (plan 6.2, строка Units/Schedule).
R.scheduleHorizon = 120        -- полосы показываем за столько секунд до прихода
R.relocateWithin = 15          -- за столько секунд полоса переезжает на выделенное место

-- Опознание юнита.
R.fractionTolerance = 0.06     -- допуск доли здоровья при опознании юнита по имени (IdOf)

-- Какие части HUD игры закрывают несколько кусков (plan 2.2, Hud.Cover). Часть скрывается,
-- только когда покрыты ВСЕ перечисленные куски; части без записи закрывает один Claim.
R.cover = {
	build = { "build.list", "uf.jewelry", "col.utility" },
}

R.summonCap = nil              -- [НЕ ПРОВЕРЕНО] лимиты призывов по видам
R.minimapZoom = nil            -- [НЕ ПРОВЕРЕНО] зум миникарты

-- Укорачивает cdmax до показываемой длительности: 0.2 приходит как пол и показывается 0.25.
function R.CooldownDuration(cdmax)
	if not cdmax or cdmax <= 0 then
		return 0
	end
	if cdmax <= R.cdFloorRaw + 0.0001 then
		return R.cdFloor
	end
	return cdmax
end

-- Список обязательных покрытий части или nil.
function R.Required(part)
	return R.cover[part]
end
